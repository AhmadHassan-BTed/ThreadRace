FontRenderer& FontRenderer::getInstance() {
    static FontRenderer instance;
    return instance;
}

FontRenderer::FontRenderer() : m_textureId(0), m_initialized(false) {}
FontRenderer::~FontRenderer() {
    if (m_textureId) {
        glDeleteTextures(1, &m_textureId);
    }
}

void FontRenderer::buildFontAtlas() {
    int atlasW = 256;
    int atlasH = 96;
    std::vector<uint8_t> pixels(atlasW * atlasH * 4, 0);

    for (int idx = 0; idx < 96; ++idx) {
        int charX = (idx % 16) * 16;
        int charY = (idx / 16) * 16;

        for (int r = 0; r < 16; ++r) {
            uint8_t rowByte = font8x16_data[idx][r];
            for (int c = 0; c < 8; ++c) {
                if (rowByte & (0x80 >> c)) {
                    int px = charX + c;
                    int py = charY + r;
                    int offset = (py * atlasW + px) * 4;
                    pixels[offset + 0] = 255;
                    pixels[offset + 1] = 255;
                    pixels[offset + 2] = 255;
                    pixels[offset + 3] = 255;
                }
            }
        }
    }

    glGenTextures(1, &m_textureId);
    glBindTexture(GL_TEXTURE_2D, m_textureId);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, atlasW, atlasH, 0, GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
    glBindTexture(GL_TEXTURE_2D, 0);

    m_initialized = true;
}

void FontRenderer::init() {
    if (!m_initialized) {
        buildFontAtlas();
    }
}

void FontRenderer::renderText(float x, float y, const std::string& text, float scale, float red, float green, float blue, float alpha) {
    if (!m_initialized) init();

    glEnable(GL_TEXTURE_2D);
    glBindTexture(GL_TEXTURE_2D, m_textureId);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glColor4f(red, green, blue, alpha);

    float curX = x;
    float charW = 10.0f * scale;
    float charH = 18.0f * scale;

    glBegin(GL_QUADS);
    for (char ch : text) {
        unsigned char c = static_cast<unsigned char>(std::toupper(static_cast<unsigned char>(ch)));
        if (c < 32 || c > 127) c = ' ';

        int idx = c - 32;
        int col = idx % 16;
        int row = idx / 16;

        float u0 = (col * 16.0f) / 256.0f;
        float v0 = (row * 16.0f) / 96.0f;
        float u1 = u0 + (8.0f / 256.0f);
        float v1 = v0 + (16.0f / 96.0f);

        glTexCoord2f(u0, v0); glVertex2f(curX, y);
        glTexCoord2f(u1, v0); glVertex2f(curX + charW, y);
        glTexCoord2f(u1, v1); glVertex2f(curX + charW, y + charH);
        glTexCoord2f(u0, v1); glVertex2f(curX, y + charH);

        curX += charW;
    }
    glEnd();

    glBindTexture(GL_TEXTURE_2D, 0);
    glDisable(GL_TEXTURE_2D);
}

void FontRenderer::renderCardHUD(float x, float y, float width, float height, const std::vector<std::string>& lines) {
    // Draw Dark Card Panel
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glColor4f(0.04f, 0.07f, 0.13f, 0.90f);

    glBegin(GL_QUADS);
    glVertex2f(x, y);
    glVertex2f(x + width, y);
    glVertex2f(x + width, y + height);
    glVertex2f(x, y + height);
    glEnd();

    // Draw Neon Border Line
    glColor4f(0.0f, 0.95f, 1.0f, 0.6f);
    glLineWidth(1.5f);
    glBegin(GL_LINE_LOOP);
    glVertex2f(x, y);
    glVertex2f(x + width, y);
    glVertex2f(x + width, y + height);
    glVertex2f(x, y + height);
    glEnd();

    // Render Text Lines
    float lineY = y + 14.0f;
    for (size_t i = 0; i < lines.size(); ++i) {
        float r = 1.0f, g = 1.0f, b = 1.0f;
        if (i == 0) { r = 0.0f; g = 0.95f; b = 1.0f; } // Cyan Title
        else if (i == 1) { r = 1.0f; g = 0.84f; b = 0.0f; } // Gold Status
        else { r = 0.85f; g = 0.90f; b = 0.95f; } // Soft White Controls

        renderText(x + 16.0f, lineY, lines[i], 0.75f, r, g, b, 0.98f);
        lineY += 22.0f;
    }
}

